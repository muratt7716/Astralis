// --------------- Context ---------------

interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string) => string;
  dir: "ltr" | "rtl";
  languageInfo: LanguageInfo;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "tr",
  setLanguage: () => {},
  t: (key: string) => key,
  dir: "ltr",
  languageInfo: languages[0],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<SupportedLanguage>("tr");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("falci-lang") as SupportedLanguage;
      if (saved && translations[saved]) {
        setLanguageState(saved);
      }
    } catch (e) {
      console.warn("localStorage is not available.");
    }
  }, []);

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    try {
      localStorage.setItem("falci-lang", lang);
    } catch (e) {
      // Ignore if localStorage is blocked
    }
    document.documentElement.dir = languages.find(l => l.code === lang)?.dir || "ltr";
    document.documentElement.lang = lang;
  };

  const t = (key: string): string => {
    return translations[language]?.[key] || translations.tr[key] || key;
  };

  const langInfo = languages.find(l => l.code === language) || languages[0];

  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      t,
      dir: langInfo.dir,
      languageInfo: langInfo,
    }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}
